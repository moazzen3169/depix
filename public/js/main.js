/**
 * 9. Contact Form AJAX Submission with PDO Backend Integration
 */
function initContactForm() {
  const form = document.getElementById('project-form');
  if (!form) return;

  const btn = form.querySelector('button[type="submit"]');
  const statusContainer = document.getElementById('form-status');

  const showStatus = (type, message) => {
    if (!statusContainer) return;

    statusContainer.className = 'mt-4 p-4 rounded-lg text-sm border';

    if (type === 'success') {
      statusContainer.classList.add('bg-green-500/10', 'text-green-400', 'border-green-500/20');
      statusContainer.innerHTML = `
        <div class="flex items-center gap-2">
          <svg class="w-5 h-5 flex-shrink-0" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M9 12l2 2 4-4m6 2a9 9 0 11-18 0 9 9 0 0118 0z" />
          </svg>
          <span>${message}</span>
        </div>
      `;
    } else if (type === 'error') {
      statusContainer.classList.add('bg-red-500/10', 'text-red-400', 'border-red-500/20');
      statusContainer.innerHTML = `
        <div class="flex items-center gap-2">
          <svg class="w-5 h-5 flex-shrink-0" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M12 9v2m0 4h.01m-6.938 4h13.856c1.54 0 2.502-1.667 1.732-3L13.732 4c-.77-1.333-2.694-1.333-3.464 0L3.34 16c-.77 1.333.192 3 1.732 3z" />
          </svg>
          <span>${message}</span>
        </div>
      `;
    }

    statusContainer.classList.remove('hidden');
  };

  form.addEventListener('submit', async (e) => {
    e.preventDefault();

    // Reset status
    if (statusContainer) statusContainer.classList.add('hidden');

    // Get Fields
    const fullName = form.querySelector('#fullName')?.value.trim() || '';
    const companyName = form.querySelector('#companyName')?.value.trim() || '';
    const phone = form.querySelector('#phone')?.value.trim() || '';
    const socialHandle = form.querySelector('#socialHandle')?.value.trim() || '';
    const projectType = form.querySelector('#projectType')?.value || '';
    const budget = form.querySelector('#budget')?.value || '';
    const projectDesc = form.querySelector('#projectDesc')?.value.trim() || '';

    // Frontend Validation
    if (!fullName) {
      showStatus('error', 'لطفاً نام و نام خانوادگی خود را وارد کنید.');
      return;
    }

    if (!phone) {
      showStatus('error', 'لطفاً شماره تماس خود را وارد کنید.');
      return;
    }

    if (!projectType) {
      showStatus('error', 'لطفاً نوع پروژه را انتخاب کنید.');
      return;
    }

    if (!projectDesc) {
      showStatus('error', 'لطفاً توضیحات پروژه خود را وارد کنید.');
      return;
    }

    // Prepare Payload
    const payload = {
      fullName,
      companyName,
      phone,
      socialHandle,
      projectType,
      budget,
      projectDesc
    };

    // Disable button & show spinner
    const origText = btn ? btn.innerHTML : '';
    if (btn) {
      btn.disabled = true;
      btn.innerHTML = `
        <svg class="animate-spin -ml-1 mr-3 h-5 w-5 text-white inline-block" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24">
          <circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"></circle>
          <path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
        </svg>
        در حال ارسال...
      `;
    }

    try {
      const response = await fetch('api/project-request.php', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json'
        },
        body: JSON.stringify(payload)
      });

      let result;
      try {
        result = await response.json();
      } catch (jsonErr) {
        throw new Error('پاسخ دریافت شده از سرور معتبر نیست.');
      }

      if (response.ok && result && result.success === true) {
        showStatus('success', result.message || 'درخواست شما با موفقیت ثبت شد!');
        form.reset();
      } else {
        const errorMsg = (result && result.message) ? result.message : 'خطایی در ثبت اطلاعات رخ داده است.';
        showStatus('error', errorMsg);
      }
    } catch (err) {
      showStatus('error', err.message || 'ارتباط با سرور برقرار نشد. لطفاً اتصال اینترنت خود را بررسی کنید.');
    } finally {
      if (btn) {
        btn.disabled = false;
        btn.innerHTML = origText;
      }
    }
  });
}

/**
 * 10. Clean Scroll Reveal / Interactive Transition Triggers
 */
function initScrollAnimations() {
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    return; // Skip animations if user requested reduced motion
  }

  const animates = document.querySelectorAll('.scroll-animate');

  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('opacity-100', 'translate-y-0');
        entry.target.classList.remove('opacity-0', 'translate-y-8');
        observer.unobserve(entry.target);
      }
    });
  }, {
    threshold: 0.1,
    rootMargin: '0px 0px -50px 0px'
  });

  animates.forEach(el => {
    el.classList.add('opacity-0', 'translate-y-8', 'transition-all-custom', 'duration-700');
    observer.observe(el);
  });
}


/**
 * Helper utilities for formatting markdown-like blog text into clean HTML
 */
function formatInlineMarkdown(text) {
  if (!text) return '';
  return text.replace(/\*\*(.*?)\*\*/g, '<strong class="font-bold text-fg-main">$1</strong>');
}

function formatBlogText(str) {
  if (!str) return '';
  const paragraphs = str.split(/\n\n+/);
  return paragraphs.map(p => {
    let trimmed = p.trim();
    if (!trimmed) return '';

    // Check if it's a blockquote starting with >
    if (trimmed.startsWith('>')) {
      const quoteContent = trimmed.replace(/^>\s*/, '');
      const formattedQuote = formatInlineMarkdown(quoteContent);
      return `<blockquote class="my-6 p-6 rounded-2xl bg-primary-accent/5 border-r-4 border-primary-accent text-base sm:text-lg font-bold text-fg-main leading-relaxed">« ${formattedQuote} »</blockquote>`;
    }

    let formatted = formatInlineMarkdown(trimmed).replace(/\n/g, '<br>');
    return `<p class="text-base sm:text-lg text-muted-fg leading-relaxed mb-6">${formatted}</p>`;
  }).join('');
}

